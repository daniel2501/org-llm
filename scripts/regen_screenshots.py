# ── Capture mechanism ────────────────────────────────────────────────

def _capture(shot: Shot, *, light: bool, out_dir: Path) -> Path | None:
    from org_llm import ui as _ui
    console = _ui.console

    # Save and override width for the duration of the capture. Rich
    # uses options-based rendering so we need to push width via the
    # Console's _width attribute (private but stable).
    prev_record = console.record
    prev_width = console._width  # noqa: SLF001 — intentional reach-in
    console.record = True
    console._width = shot.width  # noqa: SLF001
    if hasattr(console, "_record_buffer"):
        console._record_buffer.clear()  # noqa: SLF001

    try:
        try:
            shot.fn()
        except Exception:
            print(f"[{shot.name}] capture raised:", file=sys.stderr)
            traceback.print_exc()
            return None
        suffix = "-light" if light else ""
        out = out_dir / f"{shot.name}{suffix}.svg"
        theme = LIGHT_THEME if light else DARK_THEME
        console.save_svg(str(out), title=shot.title, theme=theme,
                          clear=True)  # clear=True empties the buffer post-save
        return out
    finally:
        console.record = prev_record
        console._width = prev_width  # noqa: SLF001


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                       formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", nargs="+", default=None,
                          help="Substrings to filter Shot names by")
    parser.add_argument("--no-light", action="store_true",
                          help="Skip light variants")
    parser.add_argument("--list", action="store_true",
                          help="List the registry and exit")
    parser.add_argument("--out-dir", default=str(REPO_ROOT / "docs" / "img"),
                          help="Output directory for SVGs")
    args = parser.parse_args()

    if args.list:
        for s in SHOTS:
            needs = ",".join(sorted(s.needs)) or "(none)"
            print(f"  {s.name:30}  needs={needs:10}  — {s.title}")
        return 0

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Filter
    selected = SHOTS
    if args.only:
        selected = [s for s in SHOTS
                    if any(needle.lower() in s.name.lower() for needle in args.only)]
        if not selected:
            print(f"error: no Shot names match {args.only!r}. "
                   f"Run --list to see available names.", file=sys.stderr)
            return 1

    print(f"Regenerating {len(selected)} screenshot(s) → {out_dir}")
    failures: list[str] = []
    for shot in selected:
        # Dark
        try:
            out = _capture(shot, light=False, out_dir=out_dir)
            print(f"  ✓ {out.name if out else '(failed)':40}  [dark]")
        except Exception as e:
            failures.append(f"{shot.name} (dark): {e}")
            print(f"  ✗ {shot.name:40}  [dark]  {e}", file=sys.stderr)
        # Light
        if args.no_light or shot.skip_light:
            continue
        try:
            out = _capture(shot, light=True, out_dir=out_dir)
            print(f"  ✓ {out.name if out else '(failed)':40}  [light]")
        except Exception as e:
            failures.append(f"{shot.name} (light): {e}")
            print(f"  ✗ {shot.name:40}  [light]  {e}", file=sys.stderr)

    if failures:
        print(f"\n{len(failures)} capture(s) failed:", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
