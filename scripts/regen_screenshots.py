#!/usr/bin/env python3
"""
Regenerate the docs/img/*.svg screenshots from live CLI output.

The repo ships ~33 numbered SVGs in docs/img/ (banner, doctor, splash,
askbook, captain's log, theme studio, etc.). They were generated by
Rich's `console.save_svg()` but the generation script was never
checked in — this is that script.

Run after CLI changes that affect visible output:

    uv run python scripts/regen_screenshots.py                    # all
    uv run python scripts/regen_screenshots.py --only doctor splash
    uv run python scripts/regen_screenshots.py --no-light          # dark only
    uv run python scripts/regen_screenshots.py --list              # show registry

Capture mechanism: each entry's `fn` runs against the live CLI; we
flip `org_llm.ui.console.record = True` before the call, save the
buffered segments to SVG via Rich's exporter, and restore record=False.
The same Console instance is shared across the codebase via
`from .ui import console`, so monkey-patching the attribute reaches
every print site.

Out of scope (NOT Rich-capturable, would need ttyrec/asciinema):
  • opencode TUI surfaces (home_logo, /insights dialog, sidebar) —
    those are rendered by opentui's Solid bundle, not Rich.
  • Anything inside an interactive prompt loop (askbook --interactive).

For the TUI plugin screenshots, capture them manually with your
terminal's screenshot tool while opencode is running.
"""
from __future__ import annotations

import argparse
import os
import sys
import traceback
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from rich.terminal_theme import (
    DIMMED_MONOKAI,
    MONOKAI,
    NIGHT_OWLISH,
    SVG_EXPORT_THEME,
)

# ── Theme pairs ────────────────────────────────────────────────────────
# Dark = MONOKAI (matches the existing SVGs' palette: #c5c8c6 text on
# darker bg). Light = NIGHT_OWLISH inverted via a custom theme. Both
# render the same content; only chrome colors differ.
DARK_THEME = MONOKAI
LIGHT_THEME = SVG_EXPORT_THEME  # Rich's default light export


# ── Registry ──────────────────────────────────────────────────────────

@dataclass
class Shot:
    """One screenshot entry. `fn` is called with no args; it should
    print to the shared `org_llm.ui.console`. Width is the recording
    width (Rich's default 80 is too narrow for our LCARS chrome).
    """
    name: str                  # e.g. "01-banner" — produces <name>.svg + <name>-light.svg
    title: str                 # SVG title (shown in the rich-terminal chrome)
    fn: Callable[[], None]
    needs: set[str] = field(default_factory=set)  # "db", "ollama", "vault"
    width: int = 140
    skip_light: bool = False   # some surfaces (logos with hard-coded hex) only ship dark


def _shot_banner() -> None:
    from org_llm.ui import console, PRIDE_BANNER, trans_stripe
    console.print(PRIDE_BANNER)
    console.print(trans_stripe())


def _shot_splash_classic() -> None:
    """Full LCARS splash with the active palette (assumed classic)."""
    from org_llm.ui import console
    from org_llm.cli import _render_splash_logo
    console.print(_render_splash_logo())


def _shot_palette(name: str) -> Callable[[], None]:
    """Capture the splash with a specific LCARS palette swapped in."""
    def _fn() -> None:
        from org_llm.ui import console
        from org_llm.cli import _render_splash_logo
        # Temporarily switch palette via env override, render, restore.
        prev = os.environ.get("ORG_LLM_PALETTE")
        os.environ["ORG_LLM_PALETTE"] = name
        try:
            # Force palette module to re-resolve.
            import importlib
            from org_llm import palettes as _p
            importlib.reload(_p)
            console.print(_render_splash_logo())
        finally:
            if prev is None:
                os.environ.pop("ORG_LLM_PALETTE", None)
            else:
                os.environ["ORG_LLM_PALETTE"] = prev
    return _fn


